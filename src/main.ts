import {
    LOWER_CASE,
    UPPER_CASE,
    NUMBERS,
    SPECIAL_CHARS,
    RANDOM_STRING,
    PRODUCT_KEY_CHARS,
    MIN_PASSWORD_LENGTH,
    MAX_GENERATED_PASSWORD_LENGTH,
    MIN_PRODUCT_KEY_LENGTH,
    MAX_PRODUCT_KEY_LENGTH
} from './constants';
import { InvalidInputError } from './errors';
import { inputValidator, stringCaster } from './utils/util';
import { secureRandomInt, secureShuffle } from './utils/random';
import { containsCommonWord } from './wordlist';

/** Requires at least one lower-case, upper-case, digit and non-alphanumeric char. */
const COMPLEXITY_PATTERN = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^A-Za-z0-9\s]).+$/;

const MAX_GENERATION_ATTEMPTS = 10;

function pickRandomChar(charset: string): string {
    return charset.charAt(secureRandomInt(charset.length));
}

function assertValidProductKeyLength(productKeyLength: number): void {
    const divisible = productKeyLength % 4 === 0 || productKeyLength % 5 === 0;
    if (productKeyLength < MIN_PRODUCT_KEY_LENGTH || productKeyLength > MAX_PRODUCT_KEY_LENGTH || !divisible) {
        throw new InvalidInputError();
    }
}

/**
 * Checks whether a password is strong. Returns false when the password is
 * shorter than the requested length, shorter than the minimum length,
 * missing a character class, or contains a known common word/fragment.
 * Never touches the network.
 */
export async function weakPasswordChecker(
    userPassword: unknown,
    userPasswordLength: unknown,
    additionalWords?: string[]
): Promise<boolean> {
    let rawPassword: string;
    let passwordLength: number;
    try {
        rawPassword = stringCaster(userPassword);
        passwordLength = inputValidator(userPasswordLength);
    } catch {
        return false;
    }

    if (passwordLength !== rawPassword.length || passwordLength < MIN_PASSWORD_LENGTH) {
        return false;
    }
    if (!COMPLEXITY_PATTERN.test(rawPassword)) {
        return false;
    }
    return !containsCommonWord(rawPassword, additionalWords);
}

/**
 * Appends `userPasswordLength` securely random characters drawn from
 * `obfuscatedPassword` to `autoGeneratedPassword`.
 */
export function completePasswordGeneration(
    userPasswordLength: unknown,
    autoGeneratedPassword: unknown,
    obfuscatedPassword: unknown
): string {
    const passwordLength = inputValidator(userPasswordLength);
    const prefix = autoGeneratedPassword == null ? '' : stringCaster(autoGeneratedPassword);
    const charset = stringCaster(obfuscatedPassword);
    if (charset.length === 0) {
        throw new InvalidInputError();
    }

    let generated = prefix;
    for (let i = 0; i < passwordLength; i++) {
        generated += pickRandomChar(charset);
    }
    return generated;
}

/**
 * Generates a password of exactly `userPasswordLength` characters with a
 * guaranteed mix of upper-case, lower-case, numeric and special characters,
 * then shuffles it with cryptographically secure randomness.
 * Throws InvalidInputError for lengths below MIN_PASSWORD_LENGTH.
 */
export function strongPasswordGenerator(userPasswordLength: unknown): string {
    const passwordLength = inputValidator(userPasswordLength);
    if (passwordLength < MIN_PASSWORD_LENGTH) {
        throw new InvalidInputError();
    }

    const baseLength = Math.floor(passwordLength / 4);
    const remainder = passwordLength % 4;

    const chars: string[] = [];
    for (let i = 0; i < baseLength; i++) {
        chars.push(pickRandomChar(UPPER_CASE));
        chars.push(pickRandomChar(LOWER_CASE));
        chars.push(pickRandomChar(NUMBERS));
        chars.push(pickRandomChar(SPECIAL_CHARS));
    }
    for (let i = 0; i < remainder; i++) {
        chars.push(pickRandomChar(RANDOM_STRING));
    }

    return secureShuffle(chars).join('');
}

/**
 * Generates a strong password and verifies it against weakPasswordChecker,
 * regenerating up to MAX_GENERATION_ATTEMPTS times before giving up.
 */
export async function createStrongPassword(passcodeLength: unknown): Promise<string> {
    const codeLength = inputValidator(passcodeLength);
    if (codeLength < MIN_PASSWORD_LENGTH || codeLength >= MAX_GENERATED_PASSWORD_LENGTH) {
        throw new InvalidInputError();
    }

    let candidate = '';
    for (let attempt = 0; attempt < MAX_GENERATION_ATTEMPTS; attempt++) {
        candidate = strongPasswordGenerator(codeLength);
        if (await weakPasswordChecker(candidate, codeLength)) {
            return candidate;
        }
    }
    // Practically unreachable: strongPasswordGenerator guarantees complexity.
    throw new Error('Unable to generate a strong password');
}

/**
 * Generates a product key of `rawProductKeyLength` characters grouped in
 * blocks of five (lengths divisible by 5) or four (otherwise), separated
 * by dashes. Throws InvalidInputError for unsupported lengths.
 */
export function productKeyGenerator(rawProductKeyLength: unknown): string {
    const productKeyLength = inputValidator(rawProductKeyLength);
    assertValidProductKeyLength(productKeyLength);

    const groupSize = productKeyLength % 5 === 0 ? 5 : 4;
    const chars: string[] = [];
    for (let i = 0; i < productKeyLength; i++) {
        chars.push(pickRandomChar(PRODUCT_KEY_CHARS));
    }

    const groups: string[] = [];
    for (let i = 0; i < chars.length; i += groupSize) {
        groups.push(chars.slice(i, i + groupSize).join(''));
    }
    return groups.join('-');
}

/** Generates `numberOfKeys` product keys of `rawProductKeyLength` characters each. */
export function batchProductKeyGenerator(rawProductKeyLength: unknown, numberOfKeys: unknown): string[] {
    const productKeyLength = inputValidator(rawProductKeyLength);
    const count = inputValidator(numberOfKeys);
    assertValidProductKeyLength(productKeyLength);

    const keys: string[] = [];
    for (let i = 0; i < count; i++) {
        keys.push(productKeyGenerator(productKeyLength));
    }
    return keys;
}

export { InvalidInputError };

const securePasswordUtility = {
    weakPasswordChecker,
    completePasswordGeneration,
    strongPasswordGenerator,
    createStrongPassword,
    productKeyGenerator,
    batchProductKeyGenerator
};

export default securePasswordUtility;
